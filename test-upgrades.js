const assert = require('node:assert/strict');
const game = require('./upgrades.js');
const start = { ...game.fresh(), seed: 42, cash: 1000 };
const oven = game.purchaseUpgrade(start, 'oven');
assert.equal(oven.cash, 940);
assert.equal(oven.upgradeSpending, 60);
assert.equal(start.cash, 1000);
assert.equal(start.upgrades, undefined);
assert.equal(oven.history.length, 0);
assert.throws(() => game.purchaseUpgrade(oven, 'oven'), /already/);
assert.throws(() => game.purchaseUpgrade(start, 'unknown'), /available/);
assert.throws(() => game.purchaseUpgrade({ ...start, cash: 64.99 }, 'oven'), /at least/);
assert.equal(game.purchaseUpgrade({ ...start, cash: 65 }, 'oven').cash, 5);
assert.throws(() => game.purchaseUpgrade({ ...start, history: Array(30).fill({}) }, 'oven'), /complete/);
assert.throws(() => game.purchaseUpgrade({ ...start, cash: 4 }, 'oven'), /at least/);
const all = game.purchaseUpgrade(game.purchaseUpgrade(oven, 'storefront'), 'advertising');
assert.equal(all.cash, 760);
assert.equal(all.upgradeSpending, 240);
assert.deepEqual(game.effects(all), { ingredientMultiplier: .8, demandMultiplier: 1.25, advertisingMultiplier: 2 });
assert.deepEqual(game.effects(start), { ingredientMultiplier: 1, demandMultiplier: 1, advertisingMultiplier: 1 });
// Integration checks: core simulation must consume the extension's economic hooks.
assert.equal(game.ingredientCost(oven, 'classic'), game.ingredientCost(start, 'classic') * .8);
const plainDay = game.play(start, 100, 2, 10).history[0];
const ovenDay = game.play(oven, 100, 2, 10).history[0];
assert.ok(ovenDay.ingredients < plainDay.ingredients);
assert.equal(ovenDay.ads, plainDay.ads);
assert.equal(ovenDay.expenses, ovenDay.ingredients + 10 + 5);
const storefront = game.purchaseUpgrade(start, 'storefront');
const advertising = game.purchaseUpgrade(start, 'advertising');
assert.ok(game.play(storefront, 100, 2, 10).history[0].demand > plainDay.demand);
assert.ok(game.play(advertising, 100, 2, 10).history[0].demand > plainDay.demand);
assert.equal(game.play(advertising, 100, 2, 0).history[0].demand, game.play(start, 100, 2, 0).history[0].demand);
assert.ok(game.hasUpgrade(JSON.parse(JSON.stringify(all)), 'oven'));
console.log('Upgrade checks passed: purchases, cash reserve, persistence, and real economic effects.');
