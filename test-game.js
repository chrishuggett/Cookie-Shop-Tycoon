const assert = require('node:assert/strict');
const { fresh, play } = require('./game.js');
const start = { ...fresh(), seed: 42 };
assert.equal(start.cash, 100);
assert.throws(() => play(start, 200, 2, 0), /exceeds/);
assert.throws(() => play(start, -1, 2, 0));
assert.throws(() => play(start, 1.5, 2, 0));
assert.throws(() => play(start, 1, NaN, 0));
const next = play(start, 40, 2, 5);
assert.equal(start.history.length, 0);
const r = next.history[0];
assert.equal(r.expenses, 30);
assert.equal(r.revenue, r.sold * 2);
assert.equal(next.cash, 100 + r.profit);
assert.ok(r.sold <= r.quantity && r.sold >= 0);
assert.ok(play(start, 100, 1, 0).history[0].demand > play(start, 100, 4, 0).history[0].demand);
assert.ok(play(start, 100, 2, 20).history[0].demand > play(start, 100, 2, 0).history[0].demand);
let season = { ...start, cash: 100000 };
for (let i = 0; i < 30; i++) season = play(season, 50, 2, 5);
assert.equal(season.history.length, 30);
assert.throws(() => play(season, 50, 2, 5), /complete/);
assert.throws(() => play({ ...start, cash: 4 }, 0, 2, 0), /exceeds/);
console.log('Simulation checks passed: finances, validation, demand, bankruptcy, and 30-day limit.');
